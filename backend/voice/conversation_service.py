from __future__ import annotations

from dataclasses import dataclass
import logging
import time

import requests

from core.config import CONFIG
from core.diagnostics import diagnostics_service

try:
    from openai import OpenAI

    OPENAI_AVAILABLE = True
except ImportError:
    OpenAI = None
    OPENAI_AVAILABLE = False


@dataclass
class ProviderResult:
    provider: str
    text: str


class ConversationService:
    """Routes short mirror replies across fast local-configured LLM providers."""

    def __init__(self) -> None:
        self.openai_client = None
        self._init_openai_client()

    def _init_openai_client(self) -> None:
        if not OPENAI_AVAILABLE or not CONFIG.openai_model:
            return
        if not CONFIG.openai_model or not CONFIG.openai_model.strip():
            return

        try:
            import os

            api_key = os.environ.get("OPENAI_API_KEY")
            if api_key:
                self.openai_client = OpenAI(api_key=api_key)
        except Exception:
            logging.exception("OpenAI client setup failed.")

    def respond(self, prompt: str, user_name: str, memory_context: str) -> str:
        system_prompt = self._system_prompt(user_name, memory_context)
        providers = self._provider_order()

        for provider in providers:
            started_at = time.monotonic()
            result = self._call_provider(provider, system_prompt, prompt)
            if result and result.text:
                latency_ms = int((time.monotonic() - started_at) * 1000)
                diagnostics_service.record_ai(result.provider, latency_ms)
                logging.info("AI reply generated by %s", result.provider)
                return self._polish(result.text)

        return "I need a working AI key before I can answer that."

    def _provider_order(self) -> list[str]:
        mode = CONFIG.ai_router_mode
        if mode in {"groq", "gemini", "openai"}:
            return [mode]

        # Auto mode is cost/latency efficient: fast Groq first, Gemini fallback,
        # OpenAI last only if still configured.
        order = []
        if CONFIG.groq_api_key:
            order.append("groq")
        if CONFIG.gemini_api_key:
            order.append("gemini")
        if self.openai_client:
            order.append("openai")
        return order

    def _call_provider(
        self, provider: str, system_prompt: str, user_prompt: str
    ) -> ProviderResult | None:
        try:
            if provider == "groq":
                return self._call_groq(system_prompt, user_prompt)
            if provider == "gemini":
                return self._call_gemini(system_prompt, user_prompt)
            if provider == "openai":
                return self._call_openai(system_prompt, user_prompt)
        except Exception:
            logging.exception("%s provider failed.", provider)
        return None

    def _call_groq(self, system_prompt: str, user_prompt: str) -> ProviderResult | None:
        if not CONFIG.groq_api_key:
            return None

        response = requests.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={
                "Authorization": f"Bearer {CONFIG.groq_api_key}",
                "Content-Type": "application/json",
            },
            json={
                "model": CONFIG.groq_model,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                "max_tokens": 70,
                "temperature": 0.55,
            },
            timeout=8,
        )
        response.raise_for_status()
        data = response.json()
        text = data["choices"][0]["message"]["content"]
        return ProviderResult(provider="groq", text=text)

    def _call_gemini(self, system_prompt: str, user_prompt: str) -> ProviderResult | None:
        if not CONFIG.gemini_api_key:
            return None

        model = CONFIG.gemini_model.replace("models/", "")
        response = requests.post(
            f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
            headers={
                "x-goog-api-key": CONFIG.gemini_api_key,
                "Content-Type": "application/json",
            },
            json={
                "systemInstruction": {"parts": [{"text": system_prompt}]},
                "contents": [
                    {
                        "role": "user",
                        "parts": [{"text": user_prompt}],
                    }
                ],
                "generationConfig": {
                    "maxOutputTokens": 70,
                    "temperature": 0.55,
                },
            },
            timeout=10,
        )
        response.raise_for_status()
        data = response.json()
        parts = data["candidates"][0]["content"].get("parts", [])
        text = " ".join(part.get("text", "") for part in parts).strip()
        return ProviderResult(provider="gemini", text=text)

    def _call_openai(self, system_prompt: str, user_prompt: str) -> ProviderResult | None:
        if not self.openai_client:
            return None

        response = self.openai_client.chat.completions.create(
            model=CONFIG.openai_model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            max_tokens=70,
            temperature=0.55,
        )
        return ProviderResult(
            provider="openai",
            text=response.choices[0].message.content.strip(),
        )

    def _system_prompt(self, user_name: str, memory_context: str) -> str:
        return f"""
You are an ambient AI inside a premium smart mirror.
Your voice is calm, subtle, emotionally intelligent, and concise.
Avoid clinical labels. Never say "you appear sad" or over-explain.
Use 1 short sentence unless the user clearly asks for more.
The recognized user is {user_name}.
Context: {memory_context}
""".strip()

    def _polish(self, text: str) -> str:
        text = " ".join((text or "").split())
        if len(text) <= 220:
            return text
        return text[:217].rstrip() + "..."


conversation_service = ConversationService()
